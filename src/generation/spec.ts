export interface Spec {
  version: 3;
  types: string[];
  payloads: Record<string, { properties: { name: string; type: string }[] }>;
  entities: Record<string, { payloadType: string | null; payloadNullable: boolean }>;
  eventMetadata: { type: string; nullable: boolean } | null;
}
function invalid(path: string): never {
  throw new Error(
    `Invalid EntityTracker version 3 specification at ${path}. Regenerate the spec using a compatible EntityTracker.AspNetCore version.`,
  );
}
function record(value: unknown, path: string): Record<string, any> {
  if (!value || typeof value !== "object" || Array.isArray(value)) invalid(path);
  return value as Record<string, any>;
}
const identifier = /^[A-Za-z_$][\w$]*$/;
const reserved = new Set([
  "EntityType",
  "EntityPayloadMap",
  "PayloadFor",
  "EventMetadata",
  "EntityChange",
  "EntityChangeEvent",
]);
export function validateSpec(value: unknown): asserts value is Spec {
  const spec = record(value, "$");
  if (spec.version !== 3) invalid("$.version (only version 3 is supported)");
  if (!Array.isArray(spec.types) || spec.types.some((t: unknown) => typeof t !== "string" || !t))
    invalid("$.types");
  if (new Set(spec.types).size !== spec.types.length) invalid("$.types (duplicate names)");
  const payloads = record(spec.payloads, "$.payloads");
  for (const [name, raw] of Object.entries(payloads)) {
    if (!identifier.test(name) || reserved.has(name))
      invalid(`$.payloads.${name} (invalid or reserved type name)`);
    const dto = record(raw, `$.payloads.${name}`);
    if (!Array.isArray(dto.properties)) invalid(`$.payloads.${name}.properties`);
    const names = new Set<string>();
    for (const rawProperty of dto.properties) {
      const p = record(rawProperty, `$.payloads.${name}.properties`);
      if (
        typeof p.name !== "string" ||
        !p.name ||
        names.has(p.name) ||
        typeof p.type !== "string" ||
        !p.type.trim()
      )
        invalid(`$.payloads.${name}.properties`);
      names.add(p.name);
    }
  }
  const entities = record(spec.entities, "$.entities");
  if (Object.keys(entities).length !== spec.types.length) invalid("$.entities");
  for (const name of spec.types) {
    if (!Object.hasOwn(entities, name)) invalid(`$.entities.${name}`);
    const entity = record(entities[name], `$.entities.${name}`);
    if (
      typeof entity.payloadNullable !== "boolean" ||
      (entity.payloadType !== null &&
        (typeof entity.payloadType !== "string" || !Object.hasOwn(payloads, entity.payloadType)))
    )
      invalid(`$.entities.${name}`);
  }
  if (spec.eventMetadata !== null) {
    const metadata = record(spec.eventMetadata, "$.eventMetadata");
    if (
      typeof metadata.type !== "string" ||
      !Object.hasOwn(payloads, metadata.type) ||
      typeof metadata.nullable !== "boolean"
    )
      invalid("$.eventMetadata");
  }
}

export function renderContracts(spec: Spec): string {
  const quote = (name: string) => JSON.stringify(name);
  const names = [...spec.types].sort();
  const lines = ["// Generated by @entity-tracker/react-client. Do not edit."];
  for (const name of Object.keys(spec.payloads).sort()) {
    lines.push(`export interface ${name} {`);
    for (const p of spec.payloads[name]!.properties) lines.push(`  ${quote(p.name)}: ${p.type};`);
    lines.push("}");
  }
  lines.push(
    "export const EntityType = {",
    ...names.map((n) => `  [${quote(n)}]: ${quote(n)},`),
    "} as const;",
    "export type EntityType = (typeof EntityType)[keyof typeof EntityType];",
    "export interface EntityPayloadMap {",
  );
  for (const name of names) {
    const entity = spec.entities[name]!;
    lines.push(
      `  ${quote(name)}: ${entity.payloadType === null ? "null" : entity.payloadType + (entity.payloadNullable ? " | null" : "")};`,
    );
  }
  lines.push(
    "}",
    "export type PayloadFor<T extends EntityType> = EntityPayloadMap[T];",
    `export type EventMetadata = ${spec.eventMetadata ? spec.eventMetadata.type + (spec.eventMetadata.nullable ? " | null" : "") : "null"};`,
    "export interface EntityChange<T extends EntityType = EntityType> { id: string; payload?: PayloadFor<T>; }",
    "export type EntityChangeEvent<T extends EntityType = EntityType> = T extends EntityType ? { entityType: T; changes: EntityChange<T>[]; metadata: EventMetadata; } : never;",
  );
  return lines.join("\n") + "\n";
}
